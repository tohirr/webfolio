export const GLYPHS = {};
for (const [ch, rows] of Object.entries(SRC)) {
  const lit = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < GW; x++) if (row[x] === "#") lit.push([x, y]);
  });
  GLYPHS[ch] = lit;
}

export function glyph(ch) {
  return GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? GLYPHS[" "];
}
